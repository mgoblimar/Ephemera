/// Desk theme colours (warm editorial scrapbook). Older screens use these
/// directly; new screens read [EphemeraTokens] so other themes can restyle them.
abstract final class Palette {
  static const paper = Color(0xFFF4ECDD);
  static const paperDeep = Color(0xFFE8DCC4);
  static const ink = Color(0xFF2F2A26);
  static const inkSoft = Color(0xFF6B5E52);
  static const terracotta = Color(0xFFB5603F);
  static const moss = Color(0xFF6F7F5A);
  static const kraft = Color(0xFFC9A57A);
  static const washi = Color(0xCCE8B4A0);

  /// Tints for mask overlays on the review screen, cycled per mask.
  static const maskTints = [
    Color(0xFFE07A5F),
    Color(0xFF3D8DAE),
    Color(0xFF81B29A),
    Color(0xFFF2CC8F),
    Color(0xFF9B6BB0),
    Color(0xFFD1495B),
  ];
}

/// One theme's look as data (SPEC 4.8): screens read these instead of
/// hard-coded colours, so switching theme restyles the whole app.
@immutable
class EphemeraTokens extends ThemeExtension<EphemeraTokens> {
  const EphemeraTokens({
    required this.id,
    required this.name,
    required this.paper,
    required this.paperDeep,
    required this.surface,
    required this.ink,
    required this.inkSoft,
    required this.accent,
    required this.accentSoft,
    required this.secondary,
    required this.tape,
    required this.displayFont,
    required this.bodyFont,
    required this.handFont,
    required this.cardRadius,
    required this.scrapTilt,
    required this.shadow,
  });

  final String id;
  final String name;

  /// Page-like backgrounds.
  final Color paper;
  final Color paperDeep;

  /// Cards and sheets that sit on the paper.
  final Color surface;
  final Color ink;
  final Color inkSoft;

  /// Primary actions and "selected".
  final Color accent;
  final Color accentSoft;

  /// Secondary meaning, e.g. "generated by AI" or "chosen by the agent".
  final Color secondary;

  /// Washi-tape strips used as decoration.
  final Color tape;

  final String displayFont;
  final String bodyFont;
  final String handFont;
  final double cardRadius;

  /// Max tilt, in radians, for scraps shown as physical objects.
  final double scrapTilt;
  final List<BoxShadow> shadow;

  TextStyle display(double size, {Color? color}) =>
      _font(displayFont, size, color ?? ink, FontWeight.w600);

  TextStyle hand(double size, {Color? color}) =>
      handwriting(handFont, fontSize: size, color: color ?? ink);

  @override
  EphemeraTokens copyWith({Color? accent}) => EphemeraTokens(
    id: id,
    name: name,
    paper: paper,
    paperDeep: paperDeep,
    surface: surface,
    ink: ink,
    inkSoft: inkSoft,
    accent: accent ?? this.accent,
    accentSoft: accentSoft,
    secondary: secondary,
    tape: tape,
    displayFont: displayFont,
    bodyFont: bodyFont,
    handFont: handFont,
    cardRadius: cardRadius,
    scrapTilt: scrapTilt,
    shadow: shadow,
  );

  /// Themes switch instantly; there's nothing meaningful to interpolate.
  @override
  EphemeraTokens lerp(EphemeraTokens? other, double t) =>
      t < 0.5 || other == null ? this : other;
}

