/// All themes the app offers; Cozy cat joins here (SPEC 4.8).
const themes = {'desk': deskTokens};

extension EphemeraThemeContext on BuildContext {
  EphemeraTokens get tokens =>
      Theme.of(this).extension<EphemeraTokens>() ?? deskTokens;
}

TextStyle _font(String family, double size, Color color, FontWeight weight) {
  if (!useGoogleFonts) {
    return TextStyle(
      fontFamily: family,
      fontSize: size,
      color: color,
      fontWeight: weight,
    );
  }
  return GoogleFonts.getFont(
    family,
    fontSize: size,
    color: color,
    fontWeight: weight,
  );
}

ThemeData buildTheme([EphemeraTokens tokens = deskTokens]) {
  final scheme = ColorScheme.fromSeed(
    seedColor: tokens.accent,
    primary: tokens.accent,
    secondary: tokens.secondary,
    surface: tokens.paper,
    onSurface: tokens.ink,
  );
  final base = ThemeData(colorScheme: scheme, useMaterial3: true);
  final body = useGoogleFonts
      ? GoogleFonts.getTextTheme(tokens.bodyFont, base.textTheme)
      : base.textTheme;
  final textTheme = body.copyWith(
    headlineSmall: tokens.display(24),
    titleLarge: tokens.display(22),
  );
  return base.copyWith(
    textTheme: textTheme,
    scaffoldBackgroundColor: tokens.paper,
    appBarTheme: AppBarTheme(
      backgroundColor: tokens.paper,
      foregroundColor: tokens.ink,
      elevation: 0,
      centerTitle: false,
      titleTextStyle: tokens.display(22),
    ),
    cardTheme: CardThemeData(
      color: tokens.surface,
      elevation: 0,
      shape: RoundedRectangleBorder(
        borderRadius: BorderRadius.circular(tokens.cardRadius),
      ),
    ),
    extensions: [tokens],
  );
}
